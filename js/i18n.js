let activeLanguage = "en";

export function normalizeLanguage(value) {
  if (!value) return "en";
  const lower = value.toLowerCase();
  if (lower.startsWith("ko")) return "ko";
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("zh")) return "zh";
  if (lower.startsWith("en")) return "en";
  return "en";
}

export function detectLanguage() {
  const urlLang = new URLSearchParams(window.location.search).get("lang");
  if (urlLang && SUPPORTED_LANGS.includes(normalizeLanguage(urlLang))) {
    return normalizeLanguage(urlLang);
  }
  const stored = localStorage.getItem("liferary:lang");
  if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  return normalizeLanguage(navigator.language);
}

export function setLanguage(lang, { persist = true } = {}) {
  activeLanguage = SUPPORTED_LANGS.includes(lang) ? lang : "en";
  document.documentElement.lang = activeLanguage === "zh" ? "zh-Hans" : activeLanguage;
  if (persist) localStorage.setItem("liferary:lang", activeLanguage);
}

export function getLanguage() {
  return activeLanguage;
}

export function t(key, vars = {}) {
  const template = dictionaries[activeLanguage]?.[key] ?? dictionaries.en[key] ?? key;
  return Object.entries(vars).reduce((text, [name, value]) => {
    return text.replaceAll(`{${name}}`, String(value));
  }, template);
}

export function translatePage() {
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
}

export function bindLanguageSelect(select, onChange) {
  setLanguage(detectLanguage(), { persist: false });
  if (select) {
    select.value = activeLanguage;
    select.addEventListener("change", () => {
      setLanguage(select.value);
      translatePage();
      updateSeoMeta(document.body.dataset.page);
      onChange?.(activeLanguage);
    });
  }
  translatePage();
  updateSeoMeta(document.body.dataset.page);
}

export function updateSeoMeta(page = "home") {
  if (page !== "home") {
    document.title = t("result.title");
    return;
  }

  const title = t("seo.title");
  const description = t("seo.description");
  const keywords = t("seo.keywords");
  document.title = title;
  setMeta("description", description);
  setMeta("keywords", keywords);
  setProperty("og:title", title);
  setProperty("og:description", description);
  setMeta("twitter:title", title);
  setMeta("twitter:description", description);

  const jsonLd = document.getElementById("websiteJsonLd");
  if (jsonLd) {
    const siteUrl = window.LIFERARY_CONFIG?.SITE_URL || document.querySelector("link[rel='canonical']")?.href || window.location.href;
    jsonLd.textContent = JSON.stringify({
      "@context": "https://schema.org",
      "@type": "WebSite",
      name: "Liferary",
      alternateName: "라이프러리",
      url: siteUrl,
      description,
      keywords,
      about: keywords.split(",").map((keyword) => ({
        "@type": "Thing",
        name: keyword.trim()
      })).filter((keyword) => keyword.name).slice(0, 10),
      inLanguage: ["ko", "en", "ja", "zh-Hans"],
      potentialAction: {
        "@type": "SearchAction",
        target: `${siteUrl.replace(/\/$/, "")}/result.html?id={life_id}`,
        "query-input": "required name=life_id"
      }
    });
  }
}

export function formatDateTime(value) {
  if (!value) return "";
  const locale = activeLanguage === "zh" ? "zh-CN" : activeLanguage;
  return new Intl.DateTimeFormat(locale, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit"
  }).format(new Date(value));
}

function setMeta(name, content) {
  const node = document.querySelector(`meta[name="${name}"]`);
  if (node) node.setAttribute("content", content);
}

function setProperty(property, content) {
  const node = document.querySelector(`meta[property="${property}"]`);
  if (node) node.setAttribute("content", content);
}
